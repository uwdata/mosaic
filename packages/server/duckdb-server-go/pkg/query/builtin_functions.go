// DefaultFunctions returns the reviewed local-compute functions enabled by a default allowlist.
func DefaultFunctions() []string {
	return functionNames(
		builtinOperators[:],
		builtinAggregates[:],
		builtinWindows[:],
		builtinSyntaxHelpers[:],
		builtinTableGenerators[:],
		commonScalarFunctions[:],
	)
}

// BuiltinOperators returns DuckDB operator names serialized as function nodes.
func BuiltinOperators() []string {
	return functionNames(builtinOperators[:])
}

// BuiltinAggregates returns reviewed built-in aggregate names and fixed aggregate macros.
func BuiltinAggregates() []string {
	return functionNames(builtinAggregates[:])
}

// BuiltinWindows returns reviewed built-in window function names.
func BuiltinWindows() []string {
	return functionNames(builtinWindows[:])
}

// BuiltinSyntaxHelpers returns function names synthesized for SQL syntax by DuckDB's parser.
func BuiltinSyntaxHelpers() []string {
	return functionNames(builtinSyntaxHelpers[:])
}

// BuiltinTableGenerators returns reviewed local, non-I/O table generator names.
func BuiltinTableGenerators() []string {
	return functionNames(builtinTableGenerators[:])
}

// CommonScalarFunctions returns reviewed local, side-effect-free scalar function names.
func CommonScalarFunctions() []string {
	return functionNames(commonScalarFunctions[:])
}

func functionNames(groups ...[]string) []string {
	functions := make(map[string]struct{})
	for _, group := range groups {
		for _, function := range group {
			function = strings.ToLower(strings.TrimSpace(function))
			if function != "" {
				functions[function] = struct{}{}
			}
		}
	}
	return slices.Sorted(maps.Keys(functions))
}
